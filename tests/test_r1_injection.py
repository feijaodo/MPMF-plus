def test_tagged_other_sections_parse():
    p = T.prior_reasoning(F.THINK + [{"context": "a <b> & c", "conclusion": "x\"y", "outcome": "ok", "score": .5}], 800)
    root = parse(p)
    assert [t.get("outcome") for t in root.iter("trace")] == ["ok", None, "ok"]
    assert all(len(p) <= 800 for p in [p])
    L = T.lessons(F.LESSONS3, 900, R.LESSON_FRAMING)
    root = parse(L)
    ls = list(root.iter("lesson"))
    assert [x.get("n") for x in ls] == ["1", "2", "3"] and ls[0].get("status") == "hypothesis"
    assert ls[1].get("status") is None and ls[1].text == "When D <x> happens. | E & F. | Do G."
    assert len(L) <= 900 and R.LESSON_FRAMING in L and root[0].get("truncated") is None
    L2 = T.lessons(F.LESSON, 700, R.LESSON_FRAMING)          # lesson 2 (600+ chars) does not fit: dropped, flagged
    assert [x.get("n") for x in parse(L2).iter("lesson")] == ["1"] and 'truncated="true"' in L2 and len(L2) <= 700
    assert T.lessons("", 700, R.LESSON_FRAMING) == "" and T.lessons("no items here", 700, R.LESSON_FRAMING) == ""
    V = T.verbatim(F.RAW_HITS, 500, 1500)
    assert [m.get("source") for m in parse(V).iter("message")] == ["user"] * 3
    assert T.verbatim([], 500, 1500) == "" and T.prior_reasoning([], 800) == ""


