@pytest.mark.parametrize("fmt", ["legacy", "tagged"])
def test_each_budget_changes_only_its_section(cfgfile, fmt):
    q, ids = F.CASES["temporal_cat"]

    def everything(**kw):
        cfgfile(history_additive=True, render_format=fmt, **kw)
        s = secs("temporal_cat")
        o = B.injection_opts()
        if fmt == "tagged":
            s["thinking"] = T.prior_reasoning(F.THINK, 800)
            s["lessons"] = T.lessons(F.LESSONS3, o["lessons_max_chars"] or 900, R.LESSON_FRAMING)
            s["verbatim"] = T.verbatim(F.RAW_HITS, 500, o["verbatim_max_chars"] or 1500)
        else:
            s["thinking"] = R.thinking_block(F.THINK, 800)
            s["lessons"] = R.cognition_block(F.LESSONS3, o["lessons_max_chars"] or 900)
            s["verbatim"] = RL.render(F.RAW_HITS, 500, o["verbatim_max_chars"] or 1500)
        return s
    base = everything()
    for key, val, section in (("facts_max_chars", 150, "facts"), ("history_max_chars", 200, "history"),
                              ("verbatim_max_chars", 300, "verbatim"), ("lessons_max_chars", 400, "lessons")):
        moved = everything(**{key: val})
        for other in base:
            if other == section:
                assert moved[other] != base[other], (key, other)
            else:
                assert moved[other] == base[other], (key, "changed", other)
        bigger = everything(**{key: 5000})
        for other in base:
            if other != section:
                assert bigger[other] == base[other]


